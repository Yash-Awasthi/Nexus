/**
 * `pnpm evals` — run the labelled evaluations and print the markdown that goes into docs/EVALS.md.
 *
 * `scripts/evals.mjs` owns the document (markers, `--write`, `--check`); this file owns the numbers,
 * so the table in the docs cannot be typed by hand.
 */
import { EVAL_QUERIES } from "./dataset.ts";
import {
  CHUNK_STRATEGIES,
  evaluateChunking,
  evaluateMerge,
  renderChunkingTable,
} from "./quality.ts";
import {
  DEFAULT_CONFIG,
  bestConfig,
  renderAblationTable,
  renderPerKbTable,
  runAblation,
  runRetrieval,
  worstQueries,
} from "./runner.ts";

const pct = (value: number) => `${(value * 100).toFixed(1)}%`;

export async function renderEvalReport(): Promise<string> {
  const base = await runRetrieval(DEFAULT_CONFIG);
  const ablation = await runAblation();
  const chunking = CHUNK_STRATEGIES.map((strategy) => evaluateChunking(strategy, EVAL_QUERIES));
  const merge = evaluateMerge();
  const best = bestConfig(ablation);
  const worst = worstQueries(base, 5);

  return [
    `_Generated by \`pnpm evals\` from ${EVAL_QUERIES.length} labelled queries over three knowledge bases. ` +
      "Every row below is the shipped retrieval code with a deterministic offline embedder; the labels are in " +
      "`packages/search/src/eval/dataset.ts`._",
    "",
    "### Retrieval, default configuration",
    "",
    `Default: RRF k=60, weights 0.5/0.5, no reranker, ten results. Overall n=${base.overall.n}: ` +
      `Recall@1 ${pct(base.overall.recall1)}, Recall@5 ${pct(base.overall.recall5)}, ` +
      `MRR ${pct(base.overall.mrr)}, citation accuracy ${pct(base.overall.citation)}.`,
    "",
    renderPerKbTable(base),
    "",
    "### Ablation",
    "",
    "Same queries, same embedder, only fusion/weights/rerank changed. Citation accuracy decides; MRR breaks ties.",
    "",
    renderAblationTable(ablation),
    "",
    `The winner is **${best.label}** (citation ${pct(best.report.overall.citation)}, ` +
      `MRR ${pct(best.report.overall.mrr)}). The shipped default keeps RRF 0.5/0.5 without a reranker: ` +
      `reranking wins five queries and loses one on citation (a one-sided sign test over six discordant ` +
      `queries gives p = 0.11), which is not enough evidence to change a default for every caller, and the ` +
      `one route that already reranks (\`/researcher\`) keeps doing so.`,
    "",
    "### Chunking",
    "",
    "The shipped chunker at each strategy over the same documents and queries, scored at document level " +
      "(chunks inherit their source document).",
    "",
    renderChunkingTable(chunking),
    "",
    "**Recommendation:** index whole documents while they are short. Chunking every document costs more " +
      `than it gains here — the best chunked strategy reaches ${pct(Math.max(...chunking.map((c) => c.recall5)))} ` +
      `Recall@5 against ${pct(base.overall.recall5)} for whole documents — and \`semantic\` produces three ` +
      "times as many chunks for the worst Recall@1. Chunk when a document is longer than a model's useful " +
      "context, and prefer `paragraph` (identical to `sentence` on this corpus, fewer fragments than `fixed`).",
    "",
    "### Entity merge quality",
    "",
    `Hashing \`name|type\` over ${merge.pairs} labelled pairs: precision ${pct(merge.precision)} ` +
      `(${merge.falsePositives} false positives), recall ${pct(merge.recall)} ` +
      `(${merge.falseNegatives} false negative). The hashing rule normalises NFKC, case, whitespace runs and ` +
      "trailing punctuation; it does not know synonyms, which is why `St. Louis` and `Saint Louis` stay two " +
      "nodes. A false positive would fuse two different entities silently — none in this set.",
    "",
    "### Weakest queries (default configuration)",
    "",
    ...worst.map(
      (query) =>
        `- \`${query.id}\` (${query.kb}) “${query.query}” — expected ${query.answer}, got ${query.ranked.slice(0, 3).join(", ") || "nothing"}`,
    ),
    "",
  ].join("\n");
}

if (
  import.meta.url === `file://${process.argv[1]?.replace(/\\/g, "/")}` ||
  process.argv[1]?.endsWith("cli.ts")
) {
  process.stdout.write(await renderEvalReport());
}
